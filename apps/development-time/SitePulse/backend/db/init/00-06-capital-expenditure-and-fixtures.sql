-- 00-06: Capital Expenditure & Fixtures (Demirbaş & Yatırım Projeleri) Schema (English Standard)

CREATE TABLE IF NOT EXISTS capital_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id VARCHAR(50) NOT NULL,
    title VARCHAR(180) NOT NULL,
    category VARCHAR(40) NOT NULL, -- 'ELEVATOR', 'FACADE_INSULATION', 'ROOF_WATERPROOFING', 'GENERATOR', 'SECURITY_SYSTEM', 'FIRE_SAFETY', 'OTHER'
    description TEXT,
    total_budget NUMERIC(15, 2) NOT NULL,
    allocation_basis VARCHAR(30) NOT NULL DEFAULT 'BY_LAND_SHARE', -- 'BY_LAND_SHARE', 'EQUAL_PER_UNIT'
    target_start_date DATE NOT NULL,
    target_completion_date DATE,
    contractor_name VARCHAR(150),
    contractor_tax_no VARCHAR(20),
    contractor_iban VARCHAR(34),
    contract_amount NUMERIC(15, 2),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE', -- 'PLANNED', 'ACTIVE', 'COMPLETED', 'CANCELLED'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_capital_projects_site ON capital_projects (site_id);

CREATE TABLE IF NOT EXISTS capital_project_installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES capital_projects(id) ON DELETE CASCADE,
    installment_number INT NOT NULL,
    total_installments INT NOT NULL,
    due_date DATE NOT NULL,
    installment_budget NUMERIC(15, 2) NOT NULL,
    percentage NUMERIC(5, 2) NOT NULL,
    is_accrued BOOLEAN NOT NULL DEFAULT FALSE,
    accrued_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_project_installment UNIQUE (project_id, installment_number)
);
CREATE INDEX IF NOT EXISTS idx_project_installments_proj ON capital_project_installments (project_id);

CREATE TABLE IF NOT EXISTS capital_contractor_disbursements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES capital_projects(id) ON DELETE CASCADE,
    milestone_name VARCHAR(120) NOT NULL,
    invoice_number VARCHAR(60),
    amount NUMERIC(15, 2) NOT NULL,
    disbursement_date DATE NOT NULL DEFAULT CURRENT_DATE,
    recipient_name VARCHAR(150) NOT NULL,
    recipient_iban VARCHAR(34) NOT NULL,
    payment_reference VARCHAR(100),
    disbursement_method VARCHAR(30) NOT NULL DEFAULT 'BANK_TRANSFER',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_contractor_disbursements_proj ON capital_contractor_disbursements (project_id);

