-- 00-07: Viable Relational Architecture for Occupancy, Ownership, and Identity (English Schema Standard)
-- 1. Unit Ownerships: Decouple title deed ownership from physical units and preserve historical transactions
CREATE TABLE IF NOT EXISTS unit_ownerships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    share_percentage NUMERIC(5, 2) NOT NULL DEFAULT 100.00 CHECK (share_percentage > 0 AND share_percentage <= 100.00),
    start_date DATE NOT NULL DEFAULT CURRENT_DATE,
    end_date DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_ownership_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_unit_ownerships_active ON unit_ownerships (unit_id) WHERE is_active = TRUE;
CREATE INDEX IF NOT EXISTS idx_unit_ownerships_person ON unit_ownerships (person_id);

-- Migrate existing unit owners into unit_ownerships
INSERT INTO unit_ownerships (unit_id, person_id, share_percentage, start_date, is_active)
SELECT u.id, u.owner_person_id, 100.00, COALESCE(u.created_at::date, CURRENT_DATE), true
FROM units u
WHERE u.owner_person_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM unit_ownerships uo WHERE uo.unit_id = u.id AND uo.person_id = u.owner_person_id
  );

-- 2. Occupancy Members: Scope household members to active occupancy session
CREATE TABLE IF NOT EXISTS occupancy_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occupancy_id BIGINT NOT NULL REFERENCES unit_occupancies(id) ON DELETE CASCADE,
    person_id BIGINT REFERENCES persons(id) ON DELETE SET NULL,
    full_name VARCHAR(120) NOT NULL,
    relationship VARCHAR(50) NOT NULL,
    phone VARCHAR(30),
    email VARCHAR(120),
    is_emergency_contact BOOLEAN NOT NULL DEFAULT FALSE,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_occupancy_members_occ ON occupancy_members (occupancy_id);
CREATE INDEX IF NOT EXISTS idx_occupancy_members_person ON occupancy_members (person_id);

-- 3. Multi-Tenant Role Mapping (User Site Roles)
CREATE TABLE IF NOT EXISTS user_site_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_site_role UNIQUE (user_id, site_id, role)
);
CREATE INDEX IF NOT EXISTS idx_user_site_roles_lookup ON user_site_roles (site_id, role);

-- Populate user_site_roles from existing users
INSERT INTO user_site_roles (user_id, site_id, role)
SELECT u.id, u.site_id, u.role
FROM users u
WHERE u.site_id IS NOT NULL AND u.role IS NOT NULL
ON CONFLICT ON CONSTRAINT uq_user_site_role DO NOTHING;

-- 4. Identity foreign key link on users & single source of truth in persons
ALTER TABLE users ADD COLUMN IF NOT EXISTS person_id BIGINT REFERENCES persons(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_users_person_id ON users (person_id);

-- One-time migration: copy users.full_name/phone into persons, link person_id, then drop
-- the now-redundant columns. Guarded so that every subsequent boot is a no-op.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'full_name'
    ) THEN
        INSERT INTO persons (full_name, phone, email, person_type)
        SELECT
            CASE
                WHEN u.role = 'SAAS_ADMIN' THEN 'SaaS Platform Admin'
                ELSE COALESCE(NULLIF(u.full_name, ''), 'Site User')
            END,
            COALESCE(u.phone, ''),
            u.email,
            CASE
                WHEN u.role = 'HOME_OWNER' THEN 'HOME_OWNER'
                WHEN u.role = 'HOME_RESIDENT' THEN 'HOME_RESIDENT'
                ELSE 'SITE_MANAGER'
            END
        FROM users u
        WHERE u.person_id IS NULL AND NOT EXISTS (
            SELECT 1 FROM persons p WHERE LOWER(p.email) = LOWER(u.email)
        );

        UPDATE users u
        SET person_id = p.id
        FROM persons p
        WHERE u.person_id IS NULL AND LOWER(u.email) = LOWER(p.email);

        EXECUTE 'ALTER TABLE users DROP COLUMN IF EXISTS full_name CASCADE';
        EXECUTE 'ALTER TABLE users DROP COLUMN IF EXISTS phone CASCADE';
    END IF;
END $$;

