-- 00-01: Initial PostgreSQL Schema for SitePulse Residential Management (English Schema Standard)
-- Auto-Increment BIGINT Identity Primary Keys

CREATE TABLE IF NOT EXISTS sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    block_name VARCHAR(50) NOT NULL,
    total_floors INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_blocks_site_id ON blocks (site_id);

CREATE TABLE IF NOT EXISTS persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    national_id VARCHAR(11) UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(120),
    person_type VARCHAR(20) NOT NULL -- 'HOME_OWNER', 'HOME_RESIDENT', 'SITE_MANAGER', 'SAAS_ADMIN'
);

CREATE TABLE IF NOT EXISTS units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id BIGINT NOT NULL REFERENCES blocks(id) ON DELETE CASCADE,
    unit_number INT NOT NULL,
    floor INT NOT NULL,
    land_share INT NOT NULL DEFAULT 1,
    owner_person_id BIGINT REFERENCES persons(id),
    tenant_person_id BIGINT REFERENCES persons(id),
    site_id BIGINT REFERENCES sites(id),
    virtual_iban VARCHAR(34),
    occupancy_status VARCHAR(20) NOT NULL DEFAULT 'OWNER_OCCUPIED', -- 'OWNER_OCCUPIED', 'TENANT_OCCUPIED', 'VACANT'
    house_type VARCHAR(50),
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_block_unit UNIQUE (block_id, unit_number)
);

-- Unit Occupancy History (Tracks Move-in/Move-out timeline without data loss)
CREATE TABLE IF NOT EXISTS unit_occupancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    occupancy_type VARCHAR(20) NOT NULL, -- 'OWNER' or 'TENANT'
    start_date DATE NOT NULL DEFAULT CURRENT_DATE,
    end_date DATE NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    exit_balance NUMERIC(15, 2) DEFAULT 0.00,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_occupancies_person ON unit_occupancies (person_id);

CREATE TABLE IF NOT EXISTS dues_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    period_name VARCHAR(50) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_site_period_name UNIQUE (site_id, period_name)
);
CREATE INDEX IF NOT EXISTS idx_dues_periods_site ON dues_periods (site_id);

CREATE TABLE IF NOT EXISTS dues_liabilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    period VARCHAR(50) NOT NULL, -- e.g. 'September 2026'
    debtor_type VARCHAR(20) NOT NULL DEFAULT 'TENANT', -- 'TENANT', 'OWNER'
    expense_type VARCHAR(30) NOT NULL DEFAULT 'OPERATIONAL_DUES', -- 'OPERATIONAL_DUES', 'CAPITAL_DUES'
    liable_person_id BIGINT REFERENCES persons(id),
    occupancy_id BIGINT REFERENCES unit_occupancies(id),
    principal_amount NUMERIC(15, 2) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'OVERDUE', 'PAID'
    delay_penalty NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    paid_amount NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    payment_date TIMESTAMP WITH TIME ZONE,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Performance indices for mobile queries
CREATE INDEX IF NOT EXISTS idx_dues_unit_status ON dues_liabilities (unit_id, status);

-- Tariff categories used to price monthly dues per unit
CREATE TABLE IF NOT EXISTS house_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    type_name VARCHAR(50) NOT NULL,
    dues_amount NUMERIC(15, 2) NOT NULL,
    description VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_site_house_type UNIQUE (site_id, type_name)
);
