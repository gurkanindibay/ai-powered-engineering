-- Explicit, four-eyes disposition of a debtor's advance when occupancy or title ends.
CREATE TABLE IF NOT EXISTS advance_exit_settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    request_key TEXT NOT NULL CHECK (length(trim(request_key)) BETWEEN 1 AND 100),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('PAYOUT', 'TRANSFER')),
    source_debtor VARCHAR(10) NOT NULL CHECK (source_debtor IN ('OWNER', 'TENANT')),
    target_debtor VARCHAR(10) CHECK (target_debtor IN ('OWNER', 'TENANT')),
    amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
    beneficiary_name TEXT NOT NULL CHECK (length(trim(beneficiary_name)) BETWEEN 1 AND 200),
    beneficiary_person_id BIGINT REFERENCES persons(id) ON DELETE RESTRICT,
    note TEXT,
    requested_by TEXT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    decided_by TEXT,
    decided_at TIMESTAMPTZ,
    decision_note TEXT,
    payment_reference TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_advance_exit_kind_target CHECK (
        (kind = 'PAYOUT' AND target_debtor IS NULL) OR
        (kind = 'TRANSFER' AND target_debtor IS NOT NULL AND target_debtor <> source_debtor)
    ),
    CONSTRAINT chk_advance_exit_four_eyes CHECK (decided_by IS NULL OR requested_by <> decided_by),
    CONSTRAINT chk_advance_exit_decision CHECK (
        (status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL) OR
        (status IN ('APPROVED', 'REJECTED') AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_advance_exit_settlements_request_key
    ON advance_exit_settlements (site_id, request_key);
CREATE INDEX IF NOT EXISTS idx_advance_exit_settlements_pending
    ON advance_exit_settlements (unit_id, source_debtor, created_at)
    WHERE status = 'PENDING';

-- A payout is a distinct outgoing disbursement record, never an inbound payment entry.
CREATE TABLE IF NOT EXISTS advance_exit_disbursements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    settlement_id BIGINT NOT NULL UNIQUE REFERENCES advance_exit_settlements(id) ON DELETE RESTRICT,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    debtor_type VARCHAR(10) NOT NULL CHECK (debtor_type IN ('OWNER', 'TENANT')),
    amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
    beneficiary_name TEXT NOT NULL CHECK (length(trim(beneficiary_name)) BETWEEN 1 AND 200),
    beneficiary_person_id BIGINT REFERENCES persons(id) ON DELETE RESTRICT,
    payment_reference TEXT NOT NULL CHECK (length(trim(payment_reference)) > 0),
    recorded_by TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
DROP TRIGGER IF EXISTS trg_advance_exit_disbursements_append_only ON advance_exit_disbursements;
CREATE TRIGGER trg_advance_exit_disbursements_append_only
    BEFORE UPDATE OR DELETE ON advance_exit_disbursements
    FOR EACH ROW EXECUTE FUNCTION sp_ledger_append_only();

-- Advance ledger remains append-only; new entries participate in its net balance.
ALTER TABLE advance_ledger_entries DROP CONSTRAINT IF EXISTS chk_advance_ledger_entry_type;
ALTER TABLE advance_ledger_entries ADD CONSTRAINT chk_advance_ledger_entry_type
    CHECK (entry_type IN (
        'PAYMENT_SURPLUS', 'OFFSET_APPLIED', 'VIRMAN_DEBIT', 'REFUND', 'ADJUSTMENT',
        'ADJUSTMENT_CREDIT', 'ADJUSTMENT_DEBIT', 'EXIT_PAYOUT_DEBIT',
        'EXIT_TRANSFER_DEBIT', 'EXIT_TRANSFER_CREDIT'
    ));

-- Keep the remaining V16 integrity checks when replacing its view to account for
-- the new positive transfer entry type.
CREATE OR REPLACE VIEW v_integrity_violations AS
SELECT 'advance_balance_vs_ledger' AS check_name, ab.unit_id::text || '/' || ab.debtor_type AS subject,
       ab.balance - COALESCE(l.net, 0) AS difference
FROM advance_balances ab
LEFT JOIN (
    SELECT unit_id, debtor_type,
           SUM(CASE WHEN entry_type IN ('PAYMENT_SURPLUS', 'ADJUSTMENT_CREDIT', 'EXIT_TRANSFER_CREDIT') THEN amount
                    WHEN entry_type = 'ADJUSTMENT' THEN 0
                    ELSE -amount END) AS net
    FROM advance_ledger_entries GROUP BY unit_id, debtor_type
) l ON l.unit_id = ab.unit_id AND l.debtor_type = ab.debtor_type
WHERE ab.balance <> COALESCE(l.net, 0)
UNION ALL
SELECT 'installment_percentages', project_id::text, SUM(percentage) - 100
FROM capital_project_installments GROUP BY project_id HAVING SUM(percentage) <> 100
UNION ALL
SELECT 'allocations_vs_dues_paid', d.id::text,
       (d.paid_principal + d.paid_penalty) - COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0)
FROM dues_liabilities d
LEFT JOIN payment_allocations pa ON pa.dues_liability_id = d.id
GROUP BY d.id
HAVING EXISTS (SELECT 1 FROM payment_allocations x WHERE x.dues_liability_id = d.id)
   AND (d.paid_principal + d.paid_penalty) <> COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0)
UNION ALL
SELECT 'allocations_exceed_entry_amount', e.id::text,
       COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0) - e.amount
FROM payment_entries e
JOIN payment_allocations pa ON pa.payment_entry_id = e.id
GROUP BY e.id, e.amount
HAVING COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0) > e.amount
UNION ALL
SELECT 'entry_vs_receipt_amount', e.id::text, e.amount - r.total_amount
FROM payment_entries e
JOIN payment_receipts r ON r.id = e.receipt_id
WHERE e.amount <> r.total_amount AND e.payment_channel <> 'INTER_LEDGER';

