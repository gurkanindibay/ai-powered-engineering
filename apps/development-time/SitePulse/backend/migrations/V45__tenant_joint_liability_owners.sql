-- V45: keep the titled owner(s) jointly liable for tenant dues without
-- creating duplicate ledger liabilities (KMK m.22/1).
CREATE TABLE IF NOT EXISTS dues_liability_joint_owners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    due_id BIGINT NOT NULL REFERENCES dues_liabilities(id) ON DELETE CASCADE,
    owner_person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    tenant_person_id BIGINT REFERENCES persons(id) ON DELETE SET NULL,
    liable_from DATE NOT NULL,
    liable_through DATE NOT NULL,
    CONSTRAINT chk_joint_owner_dates CHECK (liable_through >= liable_from),
    CONSTRAINT uq_due_joint_owner_interval UNIQUE (due_id, owner_person_id, liable_from, liable_through)
);

-- Backfill the owner history that already exists for tenant liabilities.
INSERT INTO dues_liability_joint_owners
    (site_id, due_id, owner_person_id, tenant_person_id, liable_from, liable_through)
SELECT u.site_id,
       d.id,
       ownership.person_id,
       d.liable_person_id,
       GREATEST(ownership.start_date, period_range.period_start),
       LEAST(COALESCE(ownership.end_date, period_range.period_end), period_range.period_end)
FROM dues_liabilities d
JOIN units u ON u.id = d.unit_id
CROSS JOIN LATERAL (
    SELECT COALESCE(
               CASE WHEN d.period_key ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
                    THEN to_date(d.period_key || '-01', 'YYYY-MM-DD') END,
               date_trunc('month', d.due_date)::date
           ) AS period_start,
           (COALESCE(
               CASE WHEN d.period_key ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'
                    THEN to_date(d.period_key || '-01', 'YYYY-MM-DD') END,
               date_trunc('month', d.due_date)::date
           ) + INTERVAL '1 month - 1 day')::date AS period_end
) period_range
JOIN unit_ownerships ownership
  ON ownership.unit_id = d.unit_id
 AND ownership.start_date <= period_range.period_end
 AND COALESCE(ownership.end_date, 'infinity'::date) >= period_range.period_start
WHERE d.debtor_type = 'TENANT'
  AND d.status NOT IN ('CANCELLED', 'PAID')
ON CONFLICT (due_id, owner_person_id, liable_from, liable_through) DO NOTHING;

CREATE INDEX IF NOT EXISTS idx_due_joint_owner_person
    ON dues_liability_joint_owners (owner_person_id, due_id);

SELECT sp_enable_tenant_rls('dues_liability_joint_owners', 'site_id = sp_tenant_site()');

ALTER TABLE payment_intents
    ADD COLUMN IF NOT EXISTS pays_tenant_liability BOOLEAN NOT NULL DEFAULT FALSE;
