-- Duplicate prevention moves from the free-text label to the key.

ALTER TABLE dues_periods ADD COLUMN IF NOT EXISTS period_key TEXT;
ALTER TABLE dues_liabilities ADD COLUMN IF NOT EXISTS period_key TEXT;

-- Where the manager sees what an accrual skipped and why, scheduled runs included.
CREATE TABLE IF NOT EXISTS dues_accrual_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id       BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    period_key    TEXT NOT NULL,
    source        TEXT NOT NULL CHECK (source IN ('MANUAL', 'SCHEDULER')),
    accrued_count INTEGER NOT NULL,
    skipped_units TEXT[] NOT NULL DEFAULT '{}',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_dues_accrual_runs_site ON dues_accrual_runs (site_id, created_at DESC);

-- Rows whose label cannot be turned into a key are reported here, never guessed.
CREATE TABLE IF NOT EXISTS dues_period_migration_issues (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    row_id     BIGINT NOT NULL,
    period     TEXT NOT NULL,
    reason     TEXT NOT NULL
);

CREATE OR REPLACE FUNCTION sp_period_key(label TEXT) RETURNS TEXT
LANGUAGE plpgsql IMMUTABLE AS $f$
DECLARE
    t TEXT := lower(translate(trim(label), 'İIıŞşĞğÜüÖöÇç', 'iiisssgguuoocc'));
    m TEXT[];
    idx INT;
BEGIN
    m := regexp_match(t, '^(\d{4})-(\d{1,2})$');
    IF m IS NOT NULL THEN
        IF m[2]::INT BETWEEN 1 AND 12 THEN
            RETURN m[1] || '-' || lpad(m[2], 2, '0');
        END IF;
        RETURN NULL;
    END IF;
    m := regexp_match(t, '^(\d{1,2})/(\d{4})$');
    IF m IS NOT NULL THEN
        IF m[1]::INT BETWEEN 1 AND 12 THEN
            RETURN m[2] || '-' || lpad(m[1], 2, '0');
        END IF;
        RETURN NULL;
    END IF;
    m := regexp_match(t, '^([a-z]+)\s+(\d{4})$');
    IF m IS NULL THEN
        RETURN NULL;
    END IF;
    idx := array_position(ARRAY['ocak','subat','mart','nisan','mayis','haziran','temmuz','agustos','eylul','ekim','kasim','aralik'], m[1]);
    IF idx IS NULL THEN
        idx := array_position(ARRAY['january','february','march','april','may','june','july','august','september','october','november','december'], m[1]);
    END IF;
    IF idx IS NULL THEN
        RETURN NULL;
    END IF;
    RETURN m[2] || '-' || lpad(idx::TEXT, 2, '0');
END
$f$;

UPDATE dues_periods SET period_key = sp_period_key(period_name) WHERE period_key IS NULL;

-- Two periods of one site that resolve to the same month: keep the oldest, report the rest.
INSERT INTO dues_period_migration_issues (table_name, row_id, period, reason)
SELECT 'dues_periods', id, period_name, 'duplicate of another period of the site for the same month'
FROM (
    SELECT id, period_name,
           row_number() OVER (PARTITION BY site_id, period_key ORDER BY id) AS rn
    FROM dues_periods WHERE period_key IS NOT NULL
) d WHERE rn > 1;
UPDATE dues_periods SET period_key = NULL
WHERE id IN (SELECT row_id FROM dues_period_migration_issues
             WHERE table_name = 'dues_periods' AND reason LIKE 'duplicate%');

INSERT INTO dues_period_migration_issues (table_name, row_id, period, reason)
SELECT 'dues_periods', id, period_name, 'label is not a month'
FROM dues_periods WHERE period_key IS NULL
  AND id NOT IN (SELECT row_id FROM dues_period_migration_issues WHERE table_name = 'dues_periods');

UPDATE dues_liabilities SET period_key = sp_period_key(period) WHERE period_key IS NULL;

INSERT INTO dues_period_migration_issues (table_name, row_id, period, reason)
SELECT 'dues_liabilities', id, period, 'duplicate of another operational liability of the unit for the same month'
FROM (
    SELECT id, period,
           row_number() OVER (PARTITION BY unit_id, period_key, expense_type ORDER BY id) AS rn
    FROM dues_liabilities WHERE period_key IS NOT NULL AND capital_project_id IS NULL AND status <> 'CANCELLED'
) d WHERE rn > 1;
UPDATE dues_liabilities SET period_key = NULL
WHERE id IN (SELECT row_id FROM dues_period_migration_issues
             WHERE table_name = 'dues_liabilities' AND reason LIKE 'duplicate%');

INSERT INTO dues_period_migration_issues (table_name, row_id, period, reason)
SELECT 'dues_liabilities', id, period, 'label is not a month'
FROM dues_liabilities WHERE period_key IS NULL AND capital_project_id IS NULL
  AND id NOT IN (SELECT row_id FROM dues_period_migration_issues WHERE table_name = 'dues_liabilities');

-- Link liabilities that still lack their period row.
UPDATE dues_liabilities dl
SET dues_period_id = dp.id
FROM units u, dues_periods dp
WHERE dl.unit_id = u.id AND dp.site_id = u.site_id AND dp.period_key = dl.period_key
  AND dl.period_key IS NOT NULL AND dl.dues_period_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_dues_periods_site_key
    ON dues_periods (site_id, period_key) WHERE period_key IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_unit_period_key_expense
    ON dues_liabilities (unit_id, period_key, expense_type)
    WHERE capital_project_id IS NULL AND period_key IS NOT NULL AND status <> 'CANCELLED';

