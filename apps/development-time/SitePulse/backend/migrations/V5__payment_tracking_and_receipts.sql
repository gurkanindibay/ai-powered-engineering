-- V5: Payment Tracking, Receipts and the Unified Payment Ledger (English Schema Standard)

CREATE TABLE IF NOT EXISTS payment_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    receipt_number VARCHAR(30) NOT NULL, -- e.g. 'TAH-2026-000142'
    sequence_number BIGINT NOT NULL,     -- Monotonically increasing per site
    payer_name VARCHAR(120) NOT NULL,
    payer_role VARCHAR(20) NOT NULL,    -- 'OWNER', 'TENANT'
    on_behalf_of_name VARCHAR(120),     -- Landlord name if paid by tenant
    on_behalf_of_role VARCHAR(20),      -- 'OWNER'
    total_amount NUMERIC(15, 2) NOT NULL,
    payment_channel VARCHAR(30) NOT NULL, -- 'VIRTUAL_IBAN', 'BANK_STATEMENT', 'CREDIT_CARD', 'MANUAL_CASH', 'INTER_LEDGER'
    channel_reference VARCHAR(100),
    allocated_principal NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    allocated_penalty NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    allocated_advance NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    allocation_breakdown JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_rent_offset_eligible BOOLEAN NOT NULL DEFAULT false,
    legal_statutory_note TEXT,
    verification_hash VARCHAR(64) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_site_receipt_number UNIQUE (site_id, receipt_number)
);
CREATE INDEX IF NOT EXISTS idx_receipts_unit ON payment_receipts (unit_id);
CREATE INDEX IF NOT EXISTS idx_receipts_site_date ON payment_receipts (site_id, issued_at DESC);

-- The single canonical payment ledger. Replaces the legacy collection_transactions
-- and homeowner_payments tables (their rows are migrated here by 00-09).
CREATE TABLE IF NOT EXISTS payment_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    payer_name VARCHAR(120) NOT NULL,
    payer_role VARCHAR(20) NOT NULL DEFAULT 'TENANT',
    receipt_id BIGINT REFERENCES payment_receipts(id) ON DELETE SET NULL,
    amount NUMERIC(15, 2) NOT NULL,
    payment_channel VARCHAR(30) NOT NULL,
    settlement_status VARCHAR(20) NOT NULL DEFAULT 'SETTLED', -- 'SETTLED', 'UNMATCHED', 'REFUNDED'
    description TEXT,
    external_reference VARCHAR(100),
    payment_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_payment_entries_unit ON payment_entries (unit_id, payment_date DESC);
CREATE INDEX IF NOT EXISTS idx_payment_entries_site_date ON payment_entries (site_id, payment_date DESC);

CREATE TABLE IF NOT EXISTS debt_aging_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    debtor_type VARCHAR(20) NOT NULL, -- 'TENANT', 'OWNER'
    current_due NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    overdue_1_30_days NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    overdue_31_60_days NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    overdue_60_plus_days NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    accrued_delay_penalty NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    total_outstanding NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    as_of_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_unit_debtor_aging UNIQUE (site_id, unit_id, debtor_type, as_of_date)
);

CREATE TABLE IF NOT EXISTS advance_balances (
    unit_id BIGINT PRIMARY KEY,
    balance NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Remembers which sender IBANs and payer names belong to a unit (statement matching)
CREATE TABLE IF NOT EXISTS unit_sender_ibans (
    sender_iban VARCHAR(34) PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    label VARCHAR(100),
    bank_name VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_unit_sender_ibans_unit ON unit_sender_ibans (unit_id);

CREATE TABLE IF NOT EXISTS unit_payer_names (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL,
    payer_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_unit_payer UNIQUE (unit_id, payer_name)
);
CREATE INDEX IF NOT EXISTS idx_unit_payer_names_unit ON unit_payer_names (unit_id);

-- Bank statement lines that could not be auto-matched to a unit
CREATE TABLE IF NOT EXISTS reconciliation_queue (
    match_id VARCHAR(100) PRIMARY KEY,
    transaction_id VARCHAR(100) NOT NULL,
    txn_date DATE NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'TRY',
    description TEXT NOT NULL,
    sender_name VARCHAR(150),
    sender_iban VARCHAR(34),
    reference_no VARCHAR(100),
    matched_unit_id BIGINT,
    matched_block VARCHAR(50),
    matched_unit_number INT,
    matched_resident_name VARCHAR(150),
    confidence_score INT NOT NULL DEFAULT 0,
    matched_due_id BIGINT,
    outstanding_balance NUMERIC(15, 2),
    amount_matches_balance BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(50) NOT NULL,
    status_code VARCHAR(50) NOT NULL,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_reconciliation_unit ON reconciliation_queue (matched_unit_id);
