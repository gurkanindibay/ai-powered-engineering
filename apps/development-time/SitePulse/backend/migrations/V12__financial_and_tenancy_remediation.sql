-- V12: Financial, Multi-Tenancy, and Relational Integrity Remediation (English Schema Standard)
-- Implements Phase 1, Phase 2, Phase 3, and Phase 5 DDL requirements.

-- 1. Relational Payment Allocations (1NF Normalization)
CREATE TABLE IF NOT EXISTS payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_entry_id BIGINT NOT NULL REFERENCES payment_entries(id) ON DELETE CASCADE,
    dues_liability_id BIGINT NOT NULL REFERENCES dues_liabilities(id) ON DELETE RESTRICT,
    principal_amount NUMERIC(15, 2) NOT NULL DEFAULT 0.00 CHECK (principal_amount >= 0),
    penalty_amount NUMERIC(15, 2) NOT NULL DEFAULT 0.00 CHECK (penalty_amount >= 0),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_allocation_total_positive CHECK ((principal_amount + penalty_amount) > 0)
);
CREATE INDEX IF NOT EXISTS idx_allocations_payment ON payment_allocations (payment_entry_id);
CREATE INDEX IF NOT EXISTS idx_allocations_liability ON payment_allocations (dues_liability_id);

-- Backfill existing single-FK payment_entries into payment_allocations
INSERT INTO payment_allocations (payment_entry_id, dues_liability_id, principal_amount, penalty_amount, created_at)
SELECT pe.id, pe.dues_liability_id, pe.amount, 0.00, COALESCE(pe.payment_date, pe.created_at, CURRENT_TIMESTAMP)
FROM payment_entries pe
WHERE pe.dues_liability_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM payment_allocations pa WHERE pa.payment_entry_id = pe.id
  );

-- 2. TBK 100 Paid Principal and Penalty Tracking
ALTER TABLE dues_liabilities
    ADD COLUMN IF NOT EXISTS paid_principal NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    ADD COLUMN IF NOT EXISTS paid_penalty NUMERIC(15, 2) NOT NULL DEFAULT 0.00;

UPDATE dues_liabilities
SET paid_principal = LEAST(paid_amount, principal_amount)
WHERE paid_amount > 0 AND paid_principal = 0;

-- 3. Advance Sub-Ledger & History
ALTER TABLE advance_balances ADD COLUMN IF NOT EXISTS debtor_type VARCHAR(20) NOT NULL DEFAULT 'TENANT';

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'advance_balances_pkey' AND conrelid = 'advance_balances'::regclass
    ) THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.key_column_usage
            WHERE table_name = 'advance_balances' AND constraint_name = 'advance_balances_pkey' AND column_name = 'debtor_type'
        ) THEN
            ALTER TABLE advance_balances DROP CONSTRAINT advance_balances_pkey;
            ALTER TABLE advance_balances ADD CONSTRAINT advance_balances_pkey PRIMARY KEY (unit_id, debtor_type);
        END IF;
    END IF;
END $$;

ALTER TABLE advance_balances DROP CONSTRAINT IF EXISTS chk_advance_debtor_type;
ALTER TABLE advance_balances ADD CONSTRAINT chk_advance_debtor_type CHECK (debtor_type IN ('OWNER', 'TENANT'));

CREATE TABLE IF NOT EXISTS advance_ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    debtor_type VARCHAR(20) NOT NULL CHECK (debtor_type IN ('OWNER', 'TENANT')),
    entry_type VARCHAR(30) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    reference_id VARCHAR(100),
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_advance_ledger_unit ON advance_ledger_entries (unit_id, debtor_type);

-- 4. Reconciliation Scoping & Tenant Isolation
ALTER TABLE reconciliation_queue
    ADD COLUMN IF NOT EXISTS site_id BIGINT REFERENCES sites(id) ON DELETE CASCADE,
    ADD COLUMN IF NOT EXISTS site_bank_account_id BIGINT REFERENCES site_bank_accounts(id) ON DELETE CASCADE;

UPDATE reconciliation_queue rq
SET site_id = COALESCE(u.site_id, 1)
FROM units u
WHERE rq.matched_unit_id = u.id AND rq.site_id IS NULL;

UPDATE reconciliation_queue SET site_id = 1 WHERE site_id IS NULL;
ALTER TABLE reconciliation_queue ALTER COLUMN site_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_reconciliation_site ON reconciliation_queue (site_id);
CREATE INDEX IF NOT EXISTS idx_reconciliation_bank_account ON reconciliation_queue (site_bank_account_id);

-- 5. Sender IBAN BCNF Primary Key Fix
ALTER TABLE unit_sender_ibans ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.key_column_usage
        WHERE table_name = 'unit_sender_ibans' AND constraint_name = 'unit_sender_ibans_pkey' AND column_name = 'sender_iban'
    ) THEN
        ALTER TABLE unit_sender_ibans DROP CONSTRAINT unit_sender_ibans_pkey;
        ALTER TABLE unit_sender_ibans ADD CONSTRAINT unit_sender_ibans_pkey PRIMARY KEY (id);
    END IF;
END $$;

ALTER TABLE unit_sender_ibans DROP CONSTRAINT IF EXISTS uq_unit_sender_iban;
ALTER TABLE unit_sender_ibans ADD CONSTRAINT uq_unit_sender_iban UNIQUE (unit_id, sender_iban);

ALTER TABLE unit_sender_ibans DROP CONSTRAINT IF EXISTS chk_sender_iban_format;
ALTER TABLE unit_sender_ibans ADD CONSTRAINT chk_sender_iban_format CHECK (sender_iban ~ '^[A-Z]{2}[0-9]{2}[A-Z0-9]{11,30}$');

-- 6. Foreign Key Relinking (Periods, Tariffs, Installments)
ALTER TABLE dues_liabilities ADD COLUMN IF NOT EXISTS dues_period_id BIGINT REFERENCES dues_periods(id) ON DELETE RESTRICT;

UPDATE dues_liabilities dl
SET dues_period_id = dp.id
FROM units u, dues_periods dp
WHERE dl.unit_id = u.id AND dp.site_id = u.site_id AND dp.period_name = dl.period AND dl.dues_period_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_dues_liabilities_period ON dues_liabilities (dues_period_id);

ALTER TABLE units ADD COLUMN IF NOT EXISTS house_type_id BIGINT REFERENCES house_types(id) ON DELETE SET NULL;

UPDATE units u
SET house_type_id = ht.id
FROM house_types ht
WHERE ht.site_id = u.site_id AND ht.type_name = u.house_type AND u.house_type_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_units_house_type ON units (house_type_id);

ALTER TABLE dues_liabilities ADD COLUMN IF NOT EXISTS capital_project_installment_id BIGINT REFERENCES capital_project_installments(id) ON DELETE RESTRICT;

UPDATE dues_liabilities dl
SET capital_project_installment_id = cpi.id
FROM capital_project_installments cpi
WHERE dl.capital_project_id = cpi.project_id
  AND dl.installment_number = cpi.installment_number
  AND dl.capital_project_installment_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_dues_liabilities_installment ON dues_liabilities (capital_project_installment_id);

-- 7. Dual Active Bank Accounts (KMK 35-f)
ALTER TABLE site_bank_accounts ADD COLUMN IF NOT EXISTS account_type VARCHAR(30) NOT NULL DEFAULT 'OPERATIONAL';
ALTER TABLE site_bank_accounts DROP CONSTRAINT IF EXISTS chk_bank_account_type;
ALTER TABLE site_bank_accounts ADD CONSTRAINT chk_bank_account_type CHECK (account_type IN ('OPERATIONAL', 'CAPITAL_RESERVE'));

DROP INDEX IF EXISTS uq_site_active_bank;
CREATE UNIQUE INDEX IF NOT EXISTS uq_site_active_bank_type ON site_bank_accounts (site_id, account_type) WHERE is_active = true;

-- 8. Timezone & Cascades
ALTER TABLE sites ADD COLUMN IF NOT EXISTS timezone VARCHAR(50) NOT NULL DEFAULT 'Europe/Istanbul';

ALTER TABLE units DROP CONSTRAINT IF EXISTS units_site_id_fkey;
ALTER TABLE units ADD CONSTRAINT units_site_id_fkey FOREIGN KEY (site_id) REFERENCES sites(id) ON DELETE CASCADE;

ALTER TABLE site_bank_accounts DROP CONSTRAINT IF EXISTS site_bank_accounts_configured_by_fkey;
ALTER TABLE site_bank_accounts ADD CONSTRAINT site_bank_accounts_configured_by_fkey FOREIGN KEY (configured_by) REFERENCES users(id) ON DELETE SET NULL;

-- 9. Constraint Hardening & Index Cleanups
ALTER TABLE dues_liabilities DROP CONSTRAINT IF EXISTS chk_dues_capital_owner_only;
ALTER TABLE dues_liabilities ADD CONSTRAINT chk_dues_capital_owner_only CHECK (expense_type <> 'CAPITAL_DUES' OR debtor_type = 'OWNER');

