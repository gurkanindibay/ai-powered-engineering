-- STORY-08-05: a title transfer may record that the seller pays the capital installments that
-- accrue after the sale. The request takes effect only after a different manager approves it
-- (four-eyes, like the advance exit settlements of V39); a pending or rejected request leaves the
-- default, where each installment goes to the owner on record at accrual.
CREATE TABLE IF NOT EXISTS seller_pays_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    seller_person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    buyer_person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    transfer_date DATE NOT NULL,
    reason TEXT NOT NULL CHECK (length(trim(reason)) >= 5),
    requested_by TEXT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    decided_by TEXT,
    decided_at TIMESTAMPTZ,
    decision_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_seller_pays_distinct_parties CHECK (seller_person_id <> buyer_person_id),
    CONSTRAINT chk_seller_pays_four_eyes CHECK (decided_by IS NULL OR requested_by <> decided_by),
    CONSTRAINT chk_seller_pays_decision CHECK (
        (status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL) OR
        (status IN ('APPROVED', 'REJECTED') AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
    )
);
-- One open request per unit and buyer; a decided request is kept as history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_seller_pays_pending
    ON seller_pays_overrides (unit_id, buyer_person_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_seller_pays_approved
    ON seller_pays_overrides (unit_id, buyer_person_id) WHERE status = 'APPROVED';

SELECT sp_enable_tenant_rls('seller_pays_overrides', 'site_id = sp_tenant_site()');
