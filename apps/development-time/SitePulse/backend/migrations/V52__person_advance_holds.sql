-- V52: an advance that outlives the occupancy or ownership that paid it.
--
-- `advance_balances` is keyed by unit and debtor role, so a surplus paid by an owner
-- or tenant stayed on the unit and silently passed to whoever held that role next.
-- When the title of a unit changes hands, the seller's advance now moves to this
-- person-scoped hold: it stays the seller's money until a payout or an approved
-- transfer, and the buyer starts with a zero advance.
--
-- The hold is mirrored in `advance_ledger_entries` through the new `person_id`
-- column: an entry with a person is a hold movement, an entry without one belongs to
-- the unit's role bucket, and `v_integrity_violations` checks both against the stored
-- balances.
CREATE TABLE IF NOT EXISTS person_advance_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE RESTRICT,
    debtor_type VARCHAR(10) NOT NULL CHECK (debtor_type IN ('OWNER', 'TENANT')),
    balance NUMERIC(15, 2) NOT NULL DEFAULT 0.00 CHECK (balance >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_person_advance_holds UNIQUE (unit_id, person_id, debtor_type)
);
CREATE INDEX IF NOT EXISTS idx_person_advance_holds_site
    ON person_advance_holds (site_id, person_id);

-- Advance ledger entries gain the entitled person of a hold movement.
ALTER TABLE advance_ledger_entries
    ADD COLUMN IF NOT EXISTS person_id BIGINT REFERENCES persons(id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_advance_ledger_entries_person
    ON advance_ledger_entries (unit_id, person_id, debtor_type)
    WHERE person_id IS NOT NULL;

ALTER TABLE advance_ledger_entries DROP CONSTRAINT IF EXISTS chk_advance_ledger_entry_type;
ALTER TABLE advance_ledger_entries ADD CONSTRAINT chk_advance_ledger_entry_type
    CHECK (entry_type IN (
        'PAYMENT_SURPLUS', 'OFFSET_APPLIED', 'VIRMAN_DEBIT', 'REFUND', 'ADJUSTMENT',
        'ADJUSTMENT_CREDIT', 'ADJUSTMENT_DEBIT', 'VIRMAN_REVERSAL', 'EXIT_PAYOUT_DEBIT',
        'EXIT_TRANSFER_DEBIT', 'EXIT_TRANSFER_CREDIT',
        'TITLE_TRANSFER_DEBIT', 'TITLE_TRANSFER_HOLD'
    ));

-- Unit-bucket integrity ignores person-scoped hold movements; the role balance and
-- each person's hold are checked against their own entries.
CREATE OR REPLACE VIEW v_integrity_violations AS
SELECT 'advance_balance_vs_ledger' AS check_name, ab.unit_id::text || '/' || ab.debtor_type AS subject,
       ab.balance - COALESCE(l.net, 0) AS difference
FROM advance_balances ab
LEFT JOIN (
    SELECT unit_id, debtor_type,
           SUM(CASE WHEN entry_type IN ('PAYMENT_SURPLUS', 'ADJUSTMENT_CREDIT', 'VIRMAN_REVERSAL', 'EXIT_TRANSFER_CREDIT') THEN amount
                    WHEN entry_type = 'ADJUSTMENT' THEN 0
                    ELSE -amount END) AS net
    FROM advance_ledger_entries
    WHERE person_id IS NULL
    GROUP BY unit_id, debtor_type
) l ON l.unit_id = ab.unit_id AND l.debtor_type = ab.debtor_type
WHERE ab.balance <> COALESCE(l.net, 0)
UNION ALL
SELECT 'person_advance_hold_vs_ledger',
       h.unit_id::text || '/' || h.person_id::text || '/' || h.debtor_type,
       h.balance - COALESCE(l.net, 0)
FROM person_advance_holds h
LEFT JOIN (
    SELECT unit_id, person_id, debtor_type,
           SUM(CASE WHEN entry_type = 'TITLE_TRANSFER_HOLD' THEN amount ELSE -amount END) AS net
    FROM advance_ledger_entries
    WHERE person_id IS NOT NULL
    GROUP BY unit_id, person_id, debtor_type
) l ON l.unit_id = h.unit_id AND l.person_id = h.person_id AND l.debtor_type = h.debtor_type
WHERE h.balance <> COALESCE(l.net, 0)
UNION ALL
SELECT 'installment_percentages', project_id::text, SUM(percentage) - 100
FROM capital_project_installments GROUP BY project_id HAVING SUM(percentage) <> 100
UNION ALL
SELECT 'allocations_vs_dues_paid', d.id::text,
       (d.paid_principal + d.paid_penalty) - COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0)
FROM dues_liabilities d
LEFT JOIN payment_allocations pa ON pa.dues_liability_id = d.id
    AND NOT EXISTS (
        SELECT 1 FROM payment_entries re
        WHERE re.id = pa.payment_entry_id AND re.settlement_status = 'REVERSED'
    )
GROUP BY d.id
HAVING EXISTS (SELECT 1 FROM payment_allocations x WHERE x.dues_liability_id = d.id)
   AND (d.paid_principal + d.paid_penalty) <> COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0)
UNION ALL
SELECT 'allocations_exceed_entry_amount', e.id::text,
       COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0) - e.amount
FROM payment_entries e
JOIN payment_allocations pa ON pa.payment_entry_id = e.id
GROUP BY e.id, e.amount
HAVING COALESCE(SUM(pa.principal_amount + pa.penalty_amount), 0) > e.amount
UNION ALL
SELECT 'entry_vs_receipt_amount', e.id::text, e.amount - r.total_amount
FROM payment_entries e
JOIN payment_receipts r ON r.id = e.receipt_id
WHERE e.amount <> r.total_amount AND e.payment_channel <> 'INTER_LEDGER'
UNION ALL
SELECT 'reversal_vs_original', re.id::text, re.amount - o.amount
FROM payment_entries re
JOIN payment_entries o ON o.id = re.reverses_entry_id
WHERE re.amount <> o.amount OR o.settlement_status <> 'REVERSED' OR re.unit_id <> o.unit_id
UNION ALL
SELECT 'reversal_receipt_vs_original', rr.id::text, rr.total_amount - original.total_amount
FROM payment_receipts rr
JOIN payment_receipts original ON original.id = rr.reverses_receipt_id
WHERE rr.total_amount <> original.total_amount
   OR rr.allocated_principal <> original.allocated_principal
   OR rr.allocated_penalty <> original.allocated_penalty
   OR rr.allocated_advance <> original.allocated_advance
UNION ALL
SELECT 'budget_shares_vs_lines', b.id::text,
       COALESCE((SELECT SUM(s.annual_amount) FROM operating_budget_unit_shares s WHERE s.budget_id = b.id), 0)
       - COALESCE((SELECT SUM(l.annual_amount) FROM operating_budget_lines l WHERE l.budget_id = b.id), 0)
FROM operating_budgets b
WHERE b.status <> 'DRAFT'
  AND COALESCE((SELECT SUM(s.annual_amount) FROM operating_budget_unit_shares s WHERE s.budget_id = b.id), 0)
      <> COALESCE((SELECT SUM(l.annual_amount) FROM operating_budget_lines l WHERE l.budget_id = b.id), 0)
UNION ALL
SELECT 'captured_intent_without_receipt', pi.id::text, pi.amount
FROM payment_intents pi
WHERE pi.status IN ('CAPTURED', 'REFUNDED')
  AND NOT EXISTS (
      SELECT 1 FROM payment_receipts r
      WHERE r.site_id = pi.site_id AND r.receipt_number = pi.receipt_number
  );

SELECT sp_enable_tenant_rls('person_advance_holds', 'site_id = sp_tenant_site()');
