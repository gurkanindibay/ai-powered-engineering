pub async fn save_collection_transaction(
    pool: &Pool,
    id: &str,
    dues_liability_id: Option<&str>,
    unit_id: Option<&str>,
    transaction_type: &str,
    paid_amount: Decimal,
    reference_code: Option<&str>,
    description: Option<&str>,
) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    let client = pool.get().await?;

    let parsed_due_id = dues_liability_id.and_then(parse_id_to_i64);
    let parsed_unit_id = unit_id.and_then(parse_id_to_i64).or(Some(14));

    let valid_due_id = if let Some(d_id) = parsed_due_id {
        let exists = client
            .query_opt("SELECT id FROM dues_liabilities WHERE id = $1", &[&d_id])
            .await?;
        if exists.is_some() {
            Some(d_id)
        } else {
            let u_id = parsed_unit_id.unwrap_or(14);
            let _ = client
                .execute(
                    r#"
                    INSERT INTO dues_liabilities (id, unit_id, period, principal_amount, due_date, status)
                    VALUES ($1, $2, 'Eylül 2026', $3, CURRENT_DATE, 'PAID')
                    ON CONFLICT (id) DO NOTHING
                    "#,
                    &[&d_id, &u_id, &paid_amount],
                )
                .await;
            Some(d_id)
        }
    } else {
        None
    };

    let parsed_tx_id = parse_id_to_i64(id);
    if let Some(num_id) = parsed_tx_id {
        client
            .execute(
                r#"
                INSERT INTO collection_transactions (id, dues_liability_id, unit_id, transaction_type, paid_amount, reference_code, description, transaction_date)
                VALUES ($1, $2, $3, $4, $5, $6, $7, CURRENT_TIMESTAMP)
                ON CONFLICT (id) DO NOTHING
                "#,
                &[
                    &num_id,
                    &valid_due_id,
                    &parsed_unit_id,
                    &transaction_type,
                    &paid_amount,
                    &reference_code,
                    &description,
                ],
            )
            .await?;
    } else {
        // Auto-increment via PostgreSQL BIGINT IDENTITY sequence
        client
            .execute(
                r#"
                INSERT INTO collection_transactions (dues_liability_id, unit_id, transaction_type, paid_amount, reference_code, description, transaction_date)
                VALUES ($1, $2, $3, $4, $5, $6, CURRENT_TIMESTAMP)
                "#,
                &[
                    &valid_due_id,
                    &parsed_unit_id,
                    &transaction_type,
                    &paid_amount,
                    &reference_code,
                    &description,
                ],
            )
            .await?;
    }

    info!(
        "Saved collection transaction (₺{}) to PostgreSQL collection_transactions with auto-increment ID",
        paid_amount
    );
    Ok(())
}

